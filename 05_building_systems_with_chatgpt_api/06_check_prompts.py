# Client for the moderation call and for the fact-check chat call.
client = OpenAI(api_key=os.getenv("OPENAI_API_KEY"))

# Chat call used by the fact check. messages in, assistant text out.
# max_completion_tokens also counts reasoning tokens on gpt-5-nano.
def get_completion_from_messages(messages,
                                 model="gpt-5-nano",
                                 temperature=1,
                                 max_completion_tokens=5000):
    response = client.chat.completions.create(
        model=model,
        messages=messages,
        temperature=temperature,
        max_completion_tokens=max_completion_tokens,  # includes reasoning tokens on gpt-5-nano
    )
    return response.choices[0].message.content

